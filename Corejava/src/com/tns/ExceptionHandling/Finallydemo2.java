// Without Exception

public class Finallydemo2 {
public static void main(String[] args) {
	try {
		System.out.println("Hii Shoaib");
	}
	catch (Exception n) {
		System.out.println(n);
	}
	finally {
		System.out.println("Welcome to java");
	}
	}
}
